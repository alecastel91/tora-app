/** `td(key, vars)` — desktop-only copy in the current app language, EN fallback. */
export function useDesktopStrings() {
  const { language } = useLanguage();
  const dict = CATALOG[language] || EN;
  return (key, vars) => {
    let s = dict[key] ?? EN[key] ?? key;
    if (vars) s = s.replace(/\{\{(\w+)\}\}/g, (m, name) => (vars[name] !== undefined ? String(vars[name]) : m));
    return s;
  };
}
